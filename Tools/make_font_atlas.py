# make_font_atlas.py — извлечение bitmap-шрифта оригинала (реверс g_pFontMgr/textFont_DrawRichText).
#   Вход:  juidata/font/DATA0.TEX (256x256, .tex = 0x24-заголовок + DDS DXT1, белые бинарные глифы на чёрном)
#          juidata/font/FONT0.BIN (223 записи по 32 байта: {float u0,v0,u1,v1; int32 page,advW,glyphH,0})
#   Выход: RawAssets/Fonts/FontAtlas0.png  — RGBA alpha-маска (RGB=белый, A=яркость → чёрный фон прозрачен)
#          Source/AsdaReborn/Private/UI/AsdaFontGlyphs.g.h — таблица глифов для Slate-виджета
#   Маппинг кодпоинт→запись: ASCII 0x20..0x7E → 128+(cp-0x20); cp1251 0x80..0xFF → cp-0x80.
#   Система-python (нужен PIL). Импорт в UE делает import_font_atlas.py (headless).
import os, io, struct, sys
import os as _os, sys as _sys
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
import asda_paths as _P
try: sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception: pass
from PIL import Image

FONTDIR = _P.JUI_FONT_DIR
PNG_OUT = os.path.join(_P.ROOT, "AstoryClient", "RawAssets", "Fonts", "FontAtlas0.png")
HDR_OUT = os.path.join(_P.ROOT, "AstoryClient", "Source", "AsdaReborn", "Private", "UI", "AsdaFontGlyphs.g.h")

def extract_atlas():
    raw = open(os.path.join(FONTDIR, "DATA0.TEX"), "rb").read()
    i = raw.find(b"DDS ")
    assert i >= 0, "нет DDS в DATA0.TEX"
    im = Image.open(io.BytesIO(raw[i:])).convert("RGBA")
    W, H = im.size
    src = im.load()
    out = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    dst = out.load()
    # Глифы белые бинарные на чёрном → alpha = яркость, RGB = белый (tint красит текст в рантайме).
    for y in range(H):
        for x in range(W):
            r, g, b, a = src[x, y]
            lum = max(r, g, b)
            dst[x, y] = (255, 255, 255, lum)
    os.makedirs(os.path.dirname(PNG_OUT), exist_ok=True)
    out.save(PNG_OUT)
    print("OK atlas %dx%d -> %s" % (W, H, PNG_OUT))
    return W, H

def gen_header(atlasW, atlasH):
    raw = open(os.path.join(FONTDIR, "FONT0.BIN"), "rb").read()
    n = len(raw) // 32
    recs = []
    for r in range(n):
        u0, v0, u1, v1, page, advW, gh, z = struct.unpack_from("<ffffiiii", raw, r * 32)
        recs.append((u0, v0, u1, v1, advW, gh))
    lines = []
    lines.append("// AUTO-GENERATED by Tools/make_font_atlas.py — НЕ РЕДАКТИРОВАТЬ вручную.")
    lines.append("// Bitmap-шрифт оригинала: FONT0.BIN (223 записи) + DATA0.TEX (256x256).")
    lines.append("// Маппинг кодпоинт->запись: ASCII 0x20..0x7E -> 128+(cp-0x20); cp1251 0x80..0xFF -> cp-0x80.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("// Один глиф атласа: UV-прямоугольник [0..1] + ширина-advance(px) + высота(px).")
    lines.append("struct FAsdaGlyph { float U0, V0, U1, V1; float AdvW; float GlyphH; };")
    lines.append("")
    lines.append("static constexpr int32 GAsdaFontAtlasW = %d;" % atlasW)
    lines.append("static constexpr int32 GAsdaFontAtlasH = %d;" % atlasH)
    lines.append("static constexpr int32 GAsdaFontGlyphCount = %d;" % n)
    lines.append("static constexpr float GAsdaFontBaseHeight = 14.0f;  // высота глифа-атласа (scale = size/14)")
    lines.append("")
    lines.append("static const FAsdaGlyph GAsdaFontGlyphs[%d] = {" % n)
    for (u0, v0, u1, v1, advW, gh) in recs:
        lines.append("    { %.6ff, %.6ff, %.6ff, %.6ff, %d.0f, %d.0f }," % (u0, v0, u1, v1, advW, gh))
    lines.append("};")
    lines.append("")
    os.makedirs(os.path.dirname(HDR_OUT), exist_ok=True)
    open(HDR_OUT, "w", encoding="utf-8").write("\n".join(lines))
    print("OK header %d глифов -> %s" % (n, HDR_OUT))

if __name__ == "__main__":
    W, H = extract_atlas()
    gen_header(W, H)
    print("ГОТОВО")
