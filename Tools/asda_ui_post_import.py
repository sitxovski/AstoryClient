def content_snapshot(root=None):
    """Снимок всех файлов под `root` (по умолчанию `CONTENT_DIR`): {относительный путь: (размер, mtime_ns)}."""
    root = root or CONTENT_DIR
    out = {}
    stack = [root]
    while stack:
        d = stack.pop()
        try:
            it = os.scandir(d)
        except OSError:
            continue
        with it:
            for e in it:
                try:
                    if e.is_dir(follow_symlinks=False):
                        stack.append(e.path)
                    else:
                        st = e.stat(follow_symlinks=False)
                        out[os.path.relpath(e.path, root)] = (st.st_size, st.st_mtime_ns)
                except OSError:
                    continue
    return out


def content_diff(before, after):
    """Различия двух снимков `content_snapshot`: [«путь: было → стало»] (новые, удалённые, изменённые)."""
    out = []
    for k in sorted(set(before) | set(after)):
        a, b = before.get(k), after.get(k)
        if a != b:
            out.append("%s: %s → %s" % (k, a or "нет", b or "нет"))
    return out


