MAX_FIELD_BYTES = 63          # 64-байтовое поле минус запас под дефект D8


def check_lengths():
    """Проверка, что ни одна наша строка не длиннее допустимого."""
    bad = []
    for i, (n, d) in PLACEHOLDER.items():
        for what, s in (('имя', n), ('описание', d)):
            if len(s.encode('cp1251', 'replace')) > MAX_FIELD_BYTES:
                bad.append((i, what, len(s.encode('cp1251', 'replace')), s))
    for i, d in RESTORED_DESC.items():
        if len(d.encode('cp1251', 'replace')) > MAX_FIELD_BYTES:
            bad.append((i, 'описание', len(d.encode('cp1251', 'replace')), d))
    return bad


def main():
    import sys
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    bad = check_lengths()
    print('пустышек переведено : %d (имя + описание)' % len(PLACEHOLDER))
    print('описаний достроено  : %d' % len(RESTORED_DESC))
    print('ложных срабатываний : %d (не трогаем)' % len(NOT_TRUNCATED))
    if bad:
        print('\n★ СЛИШКОМ ДЛИННЫЕ (> %d байт):' % MAX_FIELD_BYTES)
        for i, what, n, s in bad:
            print('   id %d %s: %d байт — %s' % (i, what, n, s))
    else:
        print('\nвсе строки укладываются в %d байт' % MAX_FIELD_BYTES)


if __name__ == '__main__':
    main()


