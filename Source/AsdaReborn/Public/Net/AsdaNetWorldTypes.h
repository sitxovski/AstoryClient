// ★★★ ВТОРОЙ КАНАЛ ЦИФР УРОНА В ЗАМАХЕ («побочный урон»), разобран 2026-09-02.
//   ЧТО ЭТО. Рядом с очередью уронов сервер шлёт ВТОРУЮ пару очередей на те же четыре шага
//   замаха: 4 × i16 и 4 × i32. У 4029 они лежат по `@+25` (i16) и `@+33` (i32), у 4027 — по
//   `@+29` и `@+37` (у 4027 перед полями стоит лишний байт `case` и i16-пара, отсюда сдвиг 4).
//   Пакеты приходят ВСЕГДА полной длины (49 б у 4029, 53 б у 4027 — `GameServer.c:78630/78645`
//   и `:78544…78633`), так что байты были и раньше, порт их просто не читал.
//
//   ЭТАЛОН — приёмник. `sub_F40670@0xF40670` (`network.c:41387`, зовётся через thunk 0x93A291):
//       for (i = 0; i < 4; ++i) { push_i16(this + 1, *(WORD*)(a2 + 2*i));
//                                 push_i32(this + 7, *(DWORD*)(a3 + 4*i)); }
//   Обе очереди живут в `pChar->effectSlots[111].gap_4C4` и чистятся `sub_93412F` ПЕРЕД
//   наполнением. Заполняются они только если очередь уронов принята (`addEntriesBounded4` = 1).
//
//   ЭТАЛОН — потребитель. `Player_ProcessAttackTick` (`entity_char.c:26903-26909`, и ещё пять
//   таких же мест) НА КАДРЕ УДАРА снимает по одному элементу из каждой очереди:
//       raw = pop_i16();  val = pop_i32();
//       if ( raw != -1 ) { if ( raw < 0 ) CCharacter_TakeDamage(АТАКУЮЩИЙ, val, 3);
//                          else           CCharacter_TakeDamage(ЦЕЛЬ,      val, 3); }
//   `CCharacter_TakeDamage@0xA2C210` с `dmgKindFlag == 3` (`entity_char.c:25847-25862`) HP НЕ
//   ТРОГАЕТ вовсе — она сразу уходит в `combatFloatingDamageText(..., damageType = 0)`, то есть
//   рисует ВСПЛЫВАЮЩУЮ ЦИФРУ над указанным персонажем (плюс строку в чат). HP по-прежнему
//   приходит полем пакета. У лука/баллисты та же пара едет В СНАРЯДЕ (`entity_char.c:27416-27417`).
//
//   ЗНАЧЕНИЕ i16 ДОКАЗАНО СЕРВЕРОМ. `sub_4C5540` (`GameServer.c:78645-78655`):
//       a6 = *((WORD*)&a2[6] + i);
//       if ( a6 != -1 && a6 < 0 )
//           sub_473360(SkillMgr, userNum, userNum, -1,
//                      *(WORD*)&user->gap_552E[24 * (a6 & 0x7FFF) + 14791],   // строка таблицы навыка
//                      a6 & 0x7FFF,                                          // ← ID НАВЫКА
//                      a2[i + 8]);                                           // ← величина (i32)
//   ⇒ младшие 15 бит i16 = id навыка-источника, бит 15 (знак) = «применить к АТАКУЮЩЕМУ»,
//   значение −1 целиком = «на этом шаге записи нет». Сервер действует только при знаке,
//   клиент рисует цифру в обоих случаях — это НЕ противоречие, а разные роли (расчёт/показ).
