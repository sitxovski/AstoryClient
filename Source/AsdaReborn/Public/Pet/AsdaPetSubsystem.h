// ══════════════════════════════ РАСКЛАДКА ДАННЫХ — ОТКУДА ВЗЯТА ═══════════════════════════════
// СЕРВЕР, прямо в `CUser` (шаг записи 265120 б):
//     +256293 WORD   m_iPetPossessionCount — доступно ячеек, дефолт 6, кламп 6..30
//                    (GameServer.c:65883, 112326-112329, 114470-114473)
//     +256297 PetSlot[30], шаг 45          (GameServer.c:34289, 34444, 34807)
//     +258997 PetSlot*                     — АКТИВНЫЙ (0 = нет) (GameServer.c:34300, 35146)
//     +259001 DWORD  tick таймера сытости  (GameServer.c:34301, 35157)
//     +259005 DWORD  tick таймера опыта, период 180000 мс (GameServer.c:35238-35247)
// `PetSlot` = 45 байт = `i32 UniqueIndex` + `PetRecord`(41). Доказано конструктивно:
//   `Pet_Add` (`sub_455C20`, GameServer.c:34812) делает `qmemcpy(слот + 4, PetRecord, 0x29)`,
//   а зануление слота (`sub_455D90`, GameServer.c:34858-34870) трогает ровно эти поля.
// `PetRecord` = 41 байт (ctor `sub_45B710`, GameServer.c:36961):
//     +0  u16 PetIndex (−1 = пусто) │ +2 char[16] Name │ +18 u8 Fullness │ +19 u8 Level
//     +20 u8 MaxLevel │ +21 u16 Exp │ +23 + 6j {u16 AbilType, i32 AbilValue}, j = 0..2
//
// ★★★ ПОПРАВКИ К ПРЕЖНИМ МАТЕРИАЛАМ (найдены при сверке 2026-09-21, доказательства построчные).
//   П1. `pet_windows_re_report.md` §4.2: «сервер +24 MaxLevel в клиентском `CPetSlot` отдельного
//       поля не имеет … это пробел». НЕВЕРНО — поле есть. Приёмник списка 6106
//       (`netRecvPetListPacket`, network.c:25644) кладёт `wire+24` в `petEntry[27]`, то есть в
//       `CPetSlot + 0x6C`. То же самое делает приём 6149 (`itemRecord[27]`, npc_mob_pet.c:7727).
//       ⚠ ПРО «+0x70 usageCount» из §4.2 отчёта: ЭТИМИ ДАННЫМИ ОН НЕ ПОДТВЕРЖДАЕТСЯ. Блок,
//       которым оригинал переносит запись, ровно 28 dword: `int petArgs[28]` (network.c:25594) и
//       `qmemcpy(itemRecordCopy, itemRecord, 0x70u)` (npc_mob_pet.c:7744) — последний индекс 27
//       это и есть `+0x6C`, а `+0x70` лежит УЖЕ ЗА блоком. Формулировка по закону
//       `dead-code-markings-suspect`: писателя `+0x70` в разобранном срезе не найдено;
//       поле не заводим и не выдумываем — при надобности реверсить отдельно.
//   П2. Там же: бонусы клиента «+0x58 / +0x60 / +0x68». НЕВЕРНО — шаг 6, а не 8:
//       `+0x58`, `+0x5E`, `+0x64` (network.c:25649-25656: `petEntry[22]`+`LOWORD(petEntry[23])`,
//       `&petEntry[23]+2`+`HIWORD(petEntry[24])`, `petEntry[25]`+`LOWORD(petEntry[26])`).
//   П3. Там же §4.3, 6105: «+10 u16 exp (+2 спар.)». НЕПОЛНО — у пакета есть ветка повышения
//       уровня: `+12 u8` (признак) и `+13 u16` (новый уровень). Их читает клиент
//       (`item_enhance.c:4695-4701`) И ИХ СТАВИТ СЕРВЕР ЭТОЙ ЖЕ СБОРКИ: в ветке роста уровня
//       `sub_456D90` пишет `v31 = 1; v32 = *(u8*)(активныйСлот + 23)` (GameServer.c:35331-35332),
//       а `v31`/`v32` лежат ВНУТРИ буфера 6105 — буфер `v27` на `ebp-0x24`, `v31` на `ebp-0x18`
//       (= +12), `v32` на `ebp-0x17` (= +13), отправка `sub_4C28F0(…, 6105, 15, …, v27, …)` на
//       :35354. ⚠ Прежняя редакция этой поправки утверждала «сервер признак не ставит» — это
//       было НЕВЕРНО (ревизия 2026-09-21). Сам код порта при этом был и остаётся верным.
//   П4. Там же §4.2: `CPetData+0x1E0` назван `nPageSlots = 6`. На деле это
//       **`PetPossessionCount`** — число ДОСТУПНЫХ ЯЧЕЕК: в него пишут приёмники 6122
//       (`item_enhance.c:5036`) и 6123 (`item_enhance.c:5090`), то есть ровно серверное
//       `m_iPetPossessionCount`. Совпадение с «6 слотов на страницу» — случайное.
//   П5. `crossref/pet.md`: `CPetSlot+0x00 itemCode` → на деле `bIsActive`;
//       `CPetData+0x26C selectedPetCode` → на деле указатель на АКТИВНЫЙ слот.
//
// ══════════════════════════════ СЕТЬ: КОНВЕРТ, РАЗМЕРЫ, ГРАБЛИ ════════════════════════════════
// C→S — конверт «С СЕКРЕТОМ» у ВСЕХ ВОСЬМИ запросов (закон `packet-envelope-two-kinds`, проверено
//   посемейно, не по аналогии): `[0..7]` скрамблированный QPC, `[8..23]` MD5 тела, `[24..]` тело.
//   Доказательство на СЕРВЕРЕ — `sub_523F00(pkt, <длина тела>, userNum, 1)`, четвёртый аргумент 1
//   ⇒ тело читается с `pkt+33` (GameServer.c:34430, 34551, 35518, 35823, 35972, 36238, 36429, 36624).
//   В порту это `UAsdaNetSubsystem::SendSecured`.
// ★ РАЗМЕРЫ ТЕЛА берутся со СТОРОНЫ СЕРВЕРА (второй аргумент того же `sub_523F00`), а не с
//   клиентского сборщика: сервер отбивает пакет по длине МОЛЧА (закон `packet-size-check-no-padding`).
// ★ `charId` ≠ `userNum` (закон `charid-vs-usernum`). У питомцев в теле C→S едет **charId (i32)**:
//   сервер сверяет первое поле с `CUser+372` (`RecvUserIndex`/`ServerUserIndex` в логах
//   GameServer.c:34440, 34563, 35835, 35983, 36251, 36441). Единственное исключение — **6148**:
//   его тело начинается сразу с `petUniqueId`, поля charId у него нет вовсе (GameServer.c:36624-36640).
//   В ОТВЕТАХ наоборот: 6104/6105 начинаются с `u16 userNum`, и только потом идёт `i32 charId`.
// ★ ПАДДИНГ В ОТВЕТАХ. Сервер шлёт пет-ответы через `sub_4C28F0(..., a7 = 1)`, а это в
//   `sub_5643E0` включает ХВОСТОВОЙ МУСОР 0..19 байт (GameServer.c: `v24 = a4 + Size + 10`).
//   Значит тело S→C проверяем «не короче N», а не «ровно N». Исключение — **6106**: он шлётся с
//   `a7 = 0` (GameServer.c:34788, 35458, 35470) и проверяется ТОЧНОЙ формулой, как в эталоне
//   (`(кадр − 15) % 46 == 0`, network.c:25630), что в терминах порта = `тело == 5 + 46·N`.
// ★ Закон `no-reentrant-net-callbacks`: обработчики пакетов НИЧЕГО не отправляют. Все запросы
//   складываются в `Pending` и уходят из `Tick` — см. `EnqueueRequest`.
//
// ══════════════════════════════════ СБРОС СЕССИИ ══════════════════════════════════════════════
// Закон `session-reset-drops-early-data`. Кто пишет состояние и когда:
//   • 6123 (число ячеек) — из `CharLogonReq` (GameServer.c:112334) И из портального входа
//     (GameServer.c:114478), то есть приходит и при смене карты;
//   • 6106 (список) — из ответа БД `UPCharPetList`; в `DBManager.exe.c` эта процедура вызывается
//     из ДВУХ мест (:3622 и :11412) — вход и портал.
//   Оба пакета приходят от ИГРОВОГО сервера, то есть ПОЗЖЕ 1021 (`EnteringWorld`), поэтому
//   зачистка на `EnteringWorld` их не съедает. Тем не менее счётчик `RxSinceReset` ведётся и
//   ненулевое значение на `EnteringWorld` пишется предупреждением — это и есть диагностика закона.
//   На `MapChanged` список НЕ стирается (`Slots` и `PetPossessionCount` переживают переход):
//   чистятся только вещи сессии сокета — «запрос в полёте» и очередь отложенных отправок.
//   ⚠ `Slots` — список ПЕРЕМЕННОЙ длины (реестр), `Reset()` на нём штатен. Массивы фиксированной
//     длины внутри `FAsdaPetSlot` (`Abil*`, 3 элемента) сбрасываются ТОЛЬКО через `Init`
//     (закон `tarray-reset-breaks-fixed-length`).
// ═══════════════════════════════════════════════════════════════════════════════════════════════
