#pragma once

#include "CoreMinimal.h"

class AActor;
class UWorld;

// Состояние перекрытия ОДНОЙ надписи. Живёт у потребителя (плашка, вывеска, облачко); реестра нет.
struct FAsdaOccludeState
{
	float  Alpha = 1.f;          // показанная непрозрачность 0..1 (плавный ход к цели)
	double NextSampleS = 0.0;    // время мира следующего луча
	double LastS = 0.0;          // время мира прошлого вызова (шаг плавного хода)
	uint64 LastFrame = 0;        // кадр прошлого вызова: пропуск кадров ⇒ замер заново и мгновенно
	uint8  bInit = 0;            // первый луч сделан
	uint8  bOccluded = 0;        // принятое (после гистерезиса) состояние «перекрыто»
	uint8  Votes = 0;            // подряд лучей, не согласных с принятым состоянием
	// Сброс к «ещё не мерили» (следующий вызов пустит луч сразу и поставит непрозрачность без проявления).
	void Reset() { *this = FAsdaOccludeState(); }
};

// Что задел диагностический луч (`TraceNow`).
struct FAsdaOccludeHit
{
	bool    bOccluded = false;   // точку закрывает геометрия мира
	FVector Location = FVector::ZeroVector;   // точка попадания
	float   Distance = 0.f;      // от камеры до попадания
	FString What;                // «актор / компонент (класс)» — журнал и самотест
	int32   Skipped = 0;         // сколько попаданий отброшено (персонажи, хитбоксы, «внутри меша»)
};

namespace AsdaOverheadOcclusion
{
	// Рубильник asda.Overhead.Occlude (0 — надписи сквозь препятствия, как было до 29.10.2026).
	bool IsEnabled();

	// ★ ГЛАВНАЯ ТОЧКА. Непрозрачность надписи 0..1 с учётом перекрытия точки `Point` (мир UE) геометрией.
	//   `Owner` — владелец надписи (его коллизия не считается). Вызывать раз за кадр, пока надпись в кадре; если вызовы
	//   прерывались (надпись была вне кадра/заморожена), следующий вызов мерит сразу и ставит ответ мгновенно (без проявления
	//   устаревшего состояния). При выключенном ключе — всегда 1 и сброс состояния.
	float Evaluate(FAsdaOccludeState& S, const UWorld* W, const FVector& Point, const AActor* Owner);

	// ★★★ [ОРИГИНАЛ] 05.11.2026 (баг игроков «имена NPC видны поверх деревьев», ключ asda.Overhead.OccludeAtText): z-тест у оригинала
	//   идёт в ПИКСЕЛЯХ КВАДА надписи, а квад стоит НЕ в точке над головой — он поднят над её проекцией (плашка: якорь окна на
	//   (x − w/2, y − 50), `nameplate_positioning_re.md`; облачко и вывеска — свои сдвиги), а глубина у всех вершин — глубина точки.
	//   Крона дерева перед NPC закрывает именно эти пиксели, а точку над головой (между стволом и кроной) — часто нет. Поэтому
	//   решение берётся по СТРОКЕ ТЕКСТА: три луча (левый край, центр, правый край строки) к точкам на глубине `Anchor`, которые на
	//   экране лежат там, где нарисован текст; перекрыто ⇔ перекрыты хотя бы два (большая часть текста закрыта — у оригинала её
	//   пиксели не прошли бы z-тест). `CenterPx` — смещение центра строки от проекции `Anchor` в пикселях вьюпорта (x вправо,
	//   y вниз), `HalfWidthPx` — полуширина строки. Ключ 0 — прежнее решение по одной точке `Anchor`.
	float EvaluateText(FAsdaOccludeState& S, const UWorld* W, const FVector& Anchor, const FVector2D& CenterPx, float HalfWidthPx,
		const AActor* Owner);

	// Точка мира на глубине `Anchor` (та же плоскость, перпендикулярная взгляду), которая на экране сдвинута от проекции `Anchor`
	//   на `OffsetPx` пикселей вьюпорта. false — камеры нет (Out = Anchor).
	bool PointAtScreenOffset(const UWorld* W, const FVector& Anchor, const FVector2D& OffsetPx, FVector& Out);

	// Решение «по строке текста» включено (asda.Overhead.OccludeAtText != 0).
	bool TextSamplingOn();

	// ★★★ [ОРИГИНАЛ] 06.11.2026 (баг «плашка не поднимается на парящем маунте», ключ asda.Overhead.MountLift): подъём надписи над
	//   всадником — `Table2.heightOffset` транспорта (поле 295 `special_itemlist`, 0…108). Эталон прибавляет его к Y точки ПОСЛЕ
	//   констант типа всем над-головным окнам: плашка соседа `entityCollectNameplates` (entity_char.c:9230-9240), панель цели
	//   (game_main.c:4879-4887), своё облачко (:4478-4491), чат/вывеска (chat.c:6543-6552), запись (id 15, type 2) — ТРАНСПОРТ (имена
	//   «helmet/weapon» в декомпиле — миснейм). Поэтому и проверка перекрытия идёт от поднятой точки. 0 — не всадник или ключ 0.
	float MountLiftZ(const AActor* Owner);

	// Один луч камера → точка прямо сейчас (без состояния, без счётчика частоты). Out — подробности (может быть nullptr).
	bool TraceNow(const UWorld* W, const FVector& Point, const AActor* Owner, FAsdaOccludeHit* Out = nullptr);

	// Позиция камеры игрока этого кадра (кэш на кадр). false — камеры нет.
	bool CameraLocation(const UWorld* W, FVector& Out);

	// Счётчики с обнуления: лучей (вызовов TraceNow), запросов к физике (с повторами после отброшенных попаданий), тактов.
	void GetStats(int64& OutTraces, int64& OutQueries, uint64& OutCycles);
	void ResetStats();
}
