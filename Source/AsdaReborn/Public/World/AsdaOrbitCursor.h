//   ЗАЧЕМ. Жалоба игроков: при зажатой ПКМ камера крутится, пока курсор не упрётся в край окна или экрана, дальше поворот стоит —
//   приходится отпускать кнопку, вести курсор назад и зажимать снова.
//   ОРИГИНАЛ. Такой же дефект: `MainWndProc`, WM_MOUSEMOVE при `wParam == 2` зовёт `Camera_MouseRotate@0x959590` (game_main.c:6080,
//   render_core.c:472), а тот считает поворот по разности координат курсора и якоря, 0.01 рад/px. Курсор остаётся свободным и
//   видимым: `ClipCursor` и `SetCapture` в импортах нет, `SetCursorPos` — только центр при входе в мир (game_main.c:3442, :3862).
//   ПОРТ ДО ПРАВКИ. Поворот — дельта курсора Slate (`GetInputMouseDelta`); страж `asda.Input.ConfineCursor` держит курсор в окне, и
//   у края дельта равна нулю.
//
//   КАК УСТРОЕНО. Сторож на тикере ядра, каждый кадр решает по чистой `Decide`, держать ли захват:
//     • тик докладывает `ReportOrbit` (свой ПКМ-орбит, обзор из машины, свободная камера); доклад устарел — захвата нет, поэтому смена
//       карты, ранний выход тика или исчезнувший контроллер снимают захват сами;
//     • захват начинается, когда курсор сдвинулся на `kEngageMovePx` или кнопка держится `kEngageHoldSec`: быстрый щелчок ПКМ (меню по
//       игроку) курсор не мигает. Удержание нужно и для случая, когда курсор уже стоит у края и сдвинуться ему некуда;
//     • на время захвата — режим сырой мыши (`SetHighPrecisionMouseMode`, штатный для игр с захватом: дельта приходит мимо
//       прямоугольника зажима и края экрана), курсор ОС скрыт (`ICursor::Show`, не зависит от вида курсора порта и Alt+Z), каждый
//       кадр курсор возвращается в точку нажатия (как `FSceneViewport::OnMouseMove` при скрытии на время захвата);
//     • снятие (кнопка отпущена, потеря фокуса, сворачивание, потеря захвата вьюпорта, модальное окно через `FlushPressedKeys`):
//       сырой режим выключен, курсор показан. В точку нажатия курсор ставится только при окне на переднем плане — чужому приложению
//       курсор не двигаем (он и так стоит в ней с точностью до кадра);
//     • сырые отсчёты мыши не проходят через скорость указателя Windows: `DeltaScale` возвращает множитель уровня (в нём и ползунок
//       «Чувствительность мыши», `FAsdaCursorSpeed`), поэтому скорость поворота прежняя. Ускорение указателя Windows в сырых отсчётах
//       не повторяется.
//   Логика решения — чистая функция, самотест `asda.Camera.SelfTestOrbitCursor` гоняет её и путь игрока через события Slate.
//
//   ★★ 09.11.2026 [ИСПРАВЛЕНИЕ] ПОВОРОТ НЕ ОБРЫВАЕТСЯ ПОСРЕДИ ЗАЖИМА (ключ `asda.Camera.OrbitHoldThrough`, 0 — прежнее). Слова владельца:
//   «в некоторых точках курсор вдруг виден и вращение стоит». Причин две, обе — порт:
//     1) ЗАХВАТ МЫШИ СНИМАЕТ РЕЖИМ ВВОДА. `UAsdaWindowSubsystem::RefreshModalInput` идёт на каждом `OpenWindow` / `SetWindowVisible` /
//        `CloseWindow` (нотис, окно цели, всплывающее окно — любое окно) и ставит миру `FInputModeGameAndUI` заново; так же закрытие
//        строки чата (`UAsdaChatWindowSubsystem::CloseInput`) и показ мира (`RevealWorld`). Движок в `FInputModeGameAndUI::ApplyInputMode`
//        безусловно шлёт `ReleaseMouseCapture` (PlayerController.cpp:6407), а `FSlateApplication::ProcessReply` с ним же выключает сырой
//        режим и захват ОС (SlateApplication.cpp:3630). Без захвата `FSceneViewport::OnMouseMove` дельту не копит (SceneViewport.cpp:923)
//        — поворот стоит, а сторож видит «вьюпорт не держит мышь» и показывает курсор. ЛЕЧЕНИЕ: пока поворот идёт (доклад тика, ПКМ
//        зажата, окно на переднем плане, мир не отдан модалке — `IgnoreInput`), сторож в том же кадре возвращает вьюпорту захват
//        (`FReply::CaptureMouse` через `ProcessExternalReply` — тот же путь, что отложенные операции локального игрока), а при стоящем
//        захвате — и сырой режим со скрытым курсором. Фокус клавиатуры не трогается.
//     2) ФОКУС КЛАВИАТУРЫ УХОДИТ ПОЛЮ ВВОДА (Enter — строка чата, окно с полем). `FSceneViewport::OnFocusLost` →
//        `UGameViewportClient::LostFocus` → `FlushPressedKeys`: синтетическое отпускание ПКМ гасит `bRMBDown`, хотя кнопка зажата.
//        ЛЕЧЕНИЕ: `NoteFlush` запоминает сброс посреди поворота, `TakeRearm` в тике контроллера возвращает поворот, если Slate
//        всё ещё видит ПКМ зажатой, окно активно и мир не отдан модалке. Модальное окно (`asda.UI.ModalLockRightClick 1`), Alt+Tab,
//        сворачивание и переход карты поворот по-прежнему снимают.
#pragma once

#include "CoreMinimal.h"

struct ASDAREBORN_API FAsdaOrbitCursor
{
	static constexpr float kEngageHoldSec = 0.12f;   // удержание кнопки до захвата без сдвига курсора, с
	static constexpr float kEngageMovePx = 3.f;      // сдвиг курсора до захвата, px экрана

	// Входы решения за кадр (собирает сторож; самотест подаёт свои).
	struct FInputs
	{
		bool bKeyOn = true;              // ключ `asda.Camera.OrbitCursorLock` != 0
		bool bOrbitReported = false;     // тик докладывал поворот камеры мышью в последние кадры
		bool bButtonDown = false;        // Slate видит ПКМ зажатой
		bool bHasWindow = false;         // окно игры с хэндлом ОС есть
		bool bAppActive = false;         // приложение активно
		bool bForeground = false;        // окно игры на переднем плане ОС
		bool bMinimized = false;         // окно игры свёрнуто
		bool bViewportCaptured = false;  // вьюпорт держит захват мыши (без него сырые отсчёты до поворота не дойдут)
		float HeldSec = 0.f;             // сколько держится поворот, с
		float MovedPx = 0.f;             // насколько курсор ушёл от точки нажатия, px
	};

	// Держать ли захват при входах `In`; `bEngaged` — захват уже стоит. OutWhy — причина для журнала.
	static bool Decide(const FInputs& In, bool bEngaged, FString& OutWhy);

	// Один раз на процесс: завести сторож на тикере ядра. Повторный вызов — ничего.
	static void Startup();
	// Снять захват и убрать сторож.
	static void Shutdown();

	// Доклад из тика: мышь сейчас крутит камеру (`bHeld`). Ложный доклад не гасит истинный того же кадра.
	static void ReportOrbit(bool bHeld);
	// Множитель дельты мыши на этот кадр: при захвате — множитель скорости указателя Windows, иначе 1.
	static float DeltaScale();

	// ★ 09.11.2026: ключ `asda.Camera.OrbitHoldThrough` включён (поворот держится сквозь пересчёт режима ввода и смену фокуса).
	static bool HoldThroughOn();
	// ★ 09.11.2026: сброс клавиш контроллера (`FlushPressedKeys`); `bOrbitHeld` — в этот момент мышь крутила камеру.
	static void NoteFlush(bool bOrbitHeld);
	// ★ 09.11.2026: вернуть ли поворот после сброса клавиш (кнопка физически зажата, окно активно, модалки нет). Ответ «да» — один раз.
	static bool TakeRearm();
	// ★ 09.11.2026: сколько раз сторож возвращал вьюпорту отнятый захват (самотест).
	static int32 GetRecaptureCount();
	// ★ 09.11.2026: сколько раз поворот возвращён после сброса клавиш (самотест).
	static int32 GetRearmCount();
	// ★ 09.11.2026: тик докладывает поворот мышью (доклад живой) — самотест проверяет, что поворот снят.
	static bool IsOrbitReported();

	// Стоит ли захват.
	static bool IsEngaged();
	// Точка нажатия (экранные координаты Slate).
	static FVector2D GetAnchor();
	// Сколько раз захват ставился за процесс (самотест).
	static int32 GetEngageCount();

#if !UE_BUILD_SHIPPING
	// Самотест без окна ОС: подменить признаки окна (`bOverride` false — настоящие).
	static void DebugOverrideWindow(bool bOverride, bool bForeground);
#endif
};
