	//   ★★★ РЕВИЗИЯ fix5 (КРИТ-А): TileMax — СКОЛЬКО ПЛИТОК РАЗРЕШЕНО ВДОЛЬ ОДНОГО КУСКА. 1 = ровно
	//   поведение fix4 (одна плитка по середине полосы). Больше — полоса складывается из плиток встык,
