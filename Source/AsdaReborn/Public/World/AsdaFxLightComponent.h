	//   прямоугольника. 0 = геометрия ещё не измерена (первый кадр) ⇒ куски считаются по доле поля.
	//   ★★★ РЕВИЗИЯ fix4 (КРИТ-2): Cap — ВНЕШНЯЯ граница (уровневый потолок радиуса), но верхним
	//   пределом куска служит СОБСТВЕННЫЙ радиус источника BaseR (или доля Share, если владелец
