	// ═══ ★★★ РЕВИЗИЯ fix3 (КРИТ-1): ОДНА ФОРМУЛА РАДИУСОВ КУСКОВ — И ДЛЯ КАДРА, И ДЛЯ БЮДЖЕТА ═══
	//   Радиус куска раскладки НЕ равен «доля из поля × радиус света»: он подтягивается ВВЕРХ под
	//   длину своего куска (полу-длина ≤ 0.66·R, иначе концы куска темнеют) и вниз — уровневым
	//   потолком. У блина куски вдобавок РАЗНЫЕ: полосы-хорды у края короче, чем в середине.
	//   Пока бюджет предсказывал след по «N × доля²», он ошибался в разы: замер прогона B показал
	//   предсказание 0.98 при фактических 7.74 у блина из двух полос (радиус полосы тянется с
	//   280 до 787 юн). Поэтому геометрию раскладки считает ОДНА функция, а кадр света и бюджет
	//   её спрашивают — второй такой же расчёт разошёлся бы с первым (закон port-shared-points).
	// ★★★ РЕВИЗИЯ fix5 (КРИТ-А, 20.09.2026): ПОТОЛОК КУСКОВ ПОДНЯТ С 16 ДО 64. Полоса блина теперь
	//   складывается из НЕСКОЛЬКИХ плиток встык (иначе форма крупнее радиуса света светит чертой по
	//   середине — замер ревизии: покрытие диаметра 44 %), и 8 полос × 5 плиток = 40 кусков.
	//   Структура лежит на стеке (64 × 3 float + 64 int = 1 КБ) и заводится по одной на вызов.
	// ★★★ РЕВИЗИЯ fix6 (МЕЛК-4, 20.09.2026): ПОЛЯ ПОЗВОЛЯЮТ ЗАКАЗАТЬ БОЛЬШЕ, ЧЕМ ВМЕЩАЕТ МАССИВ.
	//   «Раскладка: источников по форме» до 16 (AsdaFxLightSpec.h:535) × «Покрытие: плиток вдоль
	//   куска» до 8 (AsdaFxLightSpec.h:614) = 128 кусков у ТРУБКИ, вдвое больше потолка. Прежде
	//   укладка молча обрывалась на 64-м куске и последние капсулы трубки оставались БЕЗ СВЕТА.
	//   Теперь потолок плиток пересчитывается под вместимость массива ДО укладки
	//   (AsdaFxTileCapForParents в .cpp, предупреждение в лог один раз за запуск): у трубки 16 × 4,
	//   у блина и кольца 8 × 8 = 64 — впритык, это сочетание не меняется. Поднимать сам потолок
	//   массива смысла нет: бюджет количества на уровне владельца 96 на ВСЮ карту, и 128 источников
	//   у одного эффекта не выдаются ни при каком уровне.
	// ★★★ ВОЛНА fix8 (пункт С-2 ревизии fix7, 20.09.2026): ПОТОЛОК ПОДНЯТ С 64 ДО 80, И ЭТО НЕ
	//   «на всякий случай», а следствие поднятого потолка ПОЛОС. При десяти полосах прежний потолок
	//   опускал плитки до 64/10 = 6 на кусок (AsdaFxTileCapForParents), а самой длинной полосе блина
	//   вдевятеро крупнее света нужно СЕМЬ: 10 × 7 = 70. Замер модели (an8_model.py, блин 9× при
	//   свете 608 и высоте замера 60 юн): массив 64 — 52 источника и 3.94 % тусклой площади,
	//   массив 80 — 56 источников и 1.99 %, то есть приёмка «не больше двух процентов» выполняется
	//   только со вторым. Цена: структура на стеке 80 × (4 float + 1 int) = 1.6 КБ вместо 1.3 КБ.
	//   ★ Побочное следствие, названное честно: у ТРУБКИ, заказавшей 16 кусков, потолок плиток
	//     поднимается с 4 до 5 — она сможет занять 80 мест вместо 64 там, где бюджет это позволит.
	enum { AsdaFxMaxSplit = 80 };
