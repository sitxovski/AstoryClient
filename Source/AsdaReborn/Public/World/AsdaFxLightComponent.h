	//   при отношении ≤ нижней кромки полосы, выход обратно в полосы — при отношении > верхней.
	//   Между ними держится ПРЕЖНЕЕ решение, поэтому дышащий радиус света не щёлкает раскладкой
	//   туда-сюда у самой границы.
	// ★★★ ВОЛНА fix9 (пункт С-2 ревизии fix8, 20.09.2026): ПОЛОСА ГИСТЕРЕЗИСА ЛЕЖИТ ПОД ПОРОГОМ,
