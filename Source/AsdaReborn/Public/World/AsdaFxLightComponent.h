	// ★★★ ВОЛНА fix9 (пункт КРИТ-1): У ЗАЩЁЛКИ ОДИН ХОЗЯИН — КАДР СВЕТА. Решение зовут ДВА места:
	//   кадр (по геометрии ЭТОГО кадра) и счёт цены в бюджете (по геометрии ПРОШЛОГО). Пока оба
