		FVector Centroid = FVector::ZeroVector;   // Σ w_i·C_i / Σ w_i — центр тяжести по вкладу
		float GeomRadius = 0.f;         // max_i(|P − C_i| + R_i) — габарит объединения секций вокруг центра тяжести
