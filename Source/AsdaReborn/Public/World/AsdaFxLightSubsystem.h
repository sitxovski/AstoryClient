	// ★★★ fix13 (КРИТ-1): ПРИВЕСТИ НАБОР СВЕТОВ К ДЕЙСТВУЮЩЕЙ СПЕЦИФИКАЦИИ.
	//   Набор (один свет на эффект против своего у каждого эмиттера) строит ТОЛЬКО RegisterEffect, а
	//   ЧИСЛА компонент перечитывает каждый тик. Поэтому запись в поля эффекта мимо
	//   PostEditChangeProperty (UE-Python `set_editor_property`, Blueprint, наш же стенд) оставляла
	//   набор от прежней спецификации: «8 поэмиттерных светов при заведении, 1 после пересканирования».
	//
	//   ★★★ ПРАВКА fix14 (С-3 и С-4 ревизии fix13, 20.09.2026). Сверка была ПО ТРЁМ СКАЛЯРАМ
	//   («свет включён», охват, кошелёк) на уровне ЭФФЕКТА — и этого мало по двум разным причинам:
	//     * С-4: состав набора зависит ещё и от спецификаций ОТДЕЛЬНЫХ эмиттеров. RegisterEffect
	//       выкидывает эмиттеры с выключенным свечением и поднимает в отборе ручные. Владелец гасит
	//       свечение одному эмиттеру — состав меняется, а сверка по трём скалярам расхождения НЕ
	//       ВИДИТ (у эффекта по-прежнему «включён, по эмиттерам, в пределах кошелька»).
	//     * С-3: скаляр «кошелёк» ловил только УМЕНЬШЕНИЕ (HavePerEmitter > Cap), то есть ПОНИЖЕНИЕ
	//       уровня чинилось само и до fix14. Сломано было ПОВЫШЕНИЕ: игрок, поднявший «Эффекты» в
	//       настройках с Low до самого верха, кошелёк увеличивает — 1 свет при кошельке 8 мимо
	//       условия проходил, и набор оставался урезанным до первого пересканирования.
	//       ★ fix15 (МЕЛК-1): 8 — это Cine (уровень 4), а Epic (3) даёт 4; по уровням кошелёк
	//       1/2/3/4/8 (`[AsdaFxLight@N] Light.FxPerEffect`, Config/DefaultScalability.ini).
	//       ★ fix15 (СРЕДН-1): дефект задевал ТОЛЬКО эффекты с охватом «свой свет у каждого
	//       эмиттера» — у охвата «один на эффект» кошелёк не читается. Таких семейств 7 из 18,
	//       включены три: char_skill, char_skill_4th, mob_skill.
	//   Теперь сверяется НЕ следствие, а сам заказ: ComputeDesiredSet даёт ровно тот список номеров
	//   эмиттеров, который построил бы RegisterEffect, и он сравнивается с фактическим поэлементно.
	//   ЕДИНАЯ функция на оба применения (закон port-shared-points): расходиться заведению и сверке
	//   нельзя, иначе сверка «чинила» бы набор каждый кадр туда-сюда.
	//   ★ Зовётся из Tick, то есть КАЖДЫЙ КАДР (а не «каждый отбор»: отбор ходит под таймером
	//   SelectIntervalSec, и при поставочном 0 это совпадает только случайно).
	//   bForce = сверить даже при `asda.Fx.Light.AutoReconcile 0`. Так зовёт её смена уровня
	//   качества: ключ отката должен снимать ПОКАДРОВУЮ страховку, а не обязанность движка
	//   ответить на то, что игрок только что подвинул ползунок в своих настройках.
	//   ★★★ ПРАВКА fix15 (СРЕДН-2 ревизии fix14): РАСХОЖДЕНИЕМ СЧИТАЕТСЯ ТОЛЬКО ТО, ЧТО ЗАВЕДЕНИЕ
	//   МОЖЕТ ЗАКРЫТЬ. При упоре в предохранитель `MaxCandidates` RegisterEffect делает break, и
	//   набор части эффектов остаётся короче заказа НАВСЕГДА — поэлементная сверка объявляла бы их
	//   расходящимися каждый кадр (заведение по всем недособранным + полный отбор). Чистая недостача
	//   при исчерпанном пределе теперь пропускается (лишний свет — по-прежнему расхождение: его
	//   заведение снесёт и освободит место), и об упоре один раз говорится в лог.
	//   Откат — `asda.Fx.Light.CeilingSkip 0`.
	void ReconcileSets(bool bForce = false);

