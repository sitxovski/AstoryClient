//     3. ★ ДВА БЮДЖЕТА, а не один. Замер волны Ф2 показал: цена НАСЫЩАЕТСЯ по количеству (от 10 до 102 светов
//        проход Lights не растёт вовсе), но растёт по РАДИУСУ (удвоение радиуса двух светов = цена сотни светов
//        обычного радиуса). Значит, честный ограничитель — площадь экранного следа: сумма (радиус/дистанция)²
//        по светящим, `[AsdaFxLight@N] Light.FxScreenBudget`. Бюджет количества `Light.FxBudget` остался как
//        грубый предохранитель (стробоскоп в бою, слабые машины), а `Light.FxRadiusCap` рубит радиус сверху.
//     4. Гистерезис: место у уже светящего отбирают, только если он прожил LeaseMinSec И претендент выигрывает
//        больше чем в LeaseHysteresis раз. Без этого на границе бюджета два соседних костра мигали бы каждый кадр.
//
//   ★ РАБОТАЕТ И В ОКНЕ РЕДАКТОРА (ShouldCreateSubsystem пропускает EWorldType::Editor). Без этого владелец
//     не мог бы крутить яркость руками: числа правятся в панели деталей, а результат был бы виден только
//     после Play. Превью-миры (EWorldType::EditorPreview, GamePreview — браузер предметов, панели превью)
//     НЕ включаются намеренно: там своя камера, свой свет и чужой бюджет ни к чему.
//     Редакторские света ассет карты НЕ ПАЧКАЮТ: компоненты создаются RF_Transient (в уровень не
//     сериализуются), а флаг «изменено» пакета уровня снимается обратно, если до нас он не был взведён.
//
//   КЛЮЧИ: asda.Fx.Light 0/1 — общий откат (0 = ни один эффект-свет не горит, «как было до Ф2»);
//          asda.Fx.Light.Editor 0/1 — показ в окне редактора отдельно от игры;
//          asda.Fx.Light.Budget — бюджет количества (>=0 ровно столько / −1 по уровню / −2 без ограничения);
//          asda.Fx.Light.ScreenBudget — экранный бюджет (>=0 / −1 по уровню / −2 без ограничения);
