// Почему так. Присед порта — донорский (AsdaFableClassic `Asda2.exe`): клип `ch4_{m|f}_05_hidewalk_01` (anim_239) играет
//   ВМЕСТО клипа хода. Клипа «присед стоя» у донора НЕТ (два метода: строки `Asda2.exe` AsdaFableClassic и WorldOfDreams,
//   список имён архива `Data/Character/Motion` — из «hide» только hidewalk_01), поэтому стоя под приседом играл обычный покой.
//   Эталон AsdaStory приседа не имеет вовсе. Своего клипа не выдумываем: поза стоя — кадр того же anim_239, удерживаемый
//   (темп 0). Кадр 10 (t = 0,333 с) — стопы проходят друг друга (разбор glb `fable_crouch/ch1_{m,f}_cremmy_preview.glb`:
//   разнос стоп по ходу ≈ −5 ед., у обоих полов одинаково); обе стопы на земле только в кадрах 18–22, но там широкий шаг.
//
// Сеть. Стоя статус приседа серверу через 4006 не передать: CharMove@0x544EB0 отвергает ход в ту же клетку (result 0, статус
//   не пишется, рассылки нет). Стоковый канал «стоя» — 4024 → 4025 (`CharEMotionSync` sub_546730: код 100…400 пишется в
//   CUser+0x54E4 и рассылается сектору, кроме себя; в ходу 4024 сток отбрасывает). Коды порта: 132 — присел стоя, 133 — встал
//   (как прыжок порта 131; эталон и донор их не шлют). Сервер должен пропускать их: `[P81_ActionCodeGuard] AllowedCodes` трёх
//   GameServer += 132–133 (иначе Mode=1 отклонит с журналом ac.other 88). Протокол и опкоды не меняются.
#pragma once

#include "CoreMinimal.h"

class AAsdaPlayerCharacter;

namespace AsdaCrouchStand
{
	constexpr int32 kStandOnCode  = 132;   // 4024/4025: присел стоя (поле CUser+0x54E4 → код @102 появления)
	constexpr int32 kStandOffCode = 133;   // 4024/4025: встал из приседа стоя
	constexpr int32 kPoseFrameDefault = 10;   // кадр anim_239 для позы стоя (30 к/с)

	// Поза приседа стоя включена ключом `asda.Crouch.StandPose`.
	bool PoseOn();
	// Время удерживаемого кадра anim_239, с (кадр ключа `asda.Crouch.StandPoseFrame` / 30, в пределах клипа).
	float PoseSec();
	// Сеть приседа стоя включена ключом `asda.Crouch.StandRelay` (отправка своих 132/133 и приём чужих 4025 / кода появления).
	bool RelayOn();
	// Показывать ли сейчас позу приседа стоя: ключ, присед на экране (`IsCrouchWalkShown`), не в воде, не в ходу, жив.
	bool Shown(const AAsdaPlayerCharacter* Ch);
	// Свой персонаж: сообщить соседям присед/вставание стоя (4024 132/133; ключ `asda.Crouch.StandRelay`). bForce — слать,
	//   даже если тот же код уже ушёл (после 4008 сервер пишет статус 0 — присед объявляется заново). Код встаёт в очередь и уходит
	//   из `TickRelay`, когда переключение отстоится 120 мс (вкл→выкл подряд — ничего), не чаще 250 мс.
	void Relay(AAsdaPlayerCharacter* Me, bool bOn, bool bForce, const TCHAR* Why);
	// Свой персонаж: досылка отложенного кода (вызывается каждый кадр из тика ввода); в ходу отложенное снимается.
	void TickRelay(AAsdaPlayerCharacter* Me);
	// Сеть: ушёл свой 4006 (ход сам несёт статус приседа — отметка «код стоя не отправлен»).
	void Note4006Sent(const AAsdaPlayerCharacter* Me);
	// Сеть: ушёл свой 4008 (сервер записал статус 0) — присевший объявляет присед стоя заново.
	void Note4008Sent(AAsdaPlayerCharacter* Me);
	// Самотест: сколько 4024 приседа стоя ушло и последний код (−1 — не было).
	int32 DebugSentCount();
	int32 DebugLastSentCode();
}
