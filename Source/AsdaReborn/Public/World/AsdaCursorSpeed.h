//   ЗАЧЕМ. Запрос владельца 19.10.2026: «чувствительность мыши» — скорость самого КУРСОРА в игре. В оригинале пункта нет.
//   ПОЧЕМУ СИСТЕМНЫЙ ВЫЗОВ. Курсор игры — системный (аппаратный, `UWidgetBlueprintLibrary::SetHardwareCursor`): его рисует
//   Windows, и скорость ему задаёт только она. Программный пересчёт (переставлять курсор `SetCursorPos` по своей дельте) даёт
//   дрожание: между кадрами Windows уже провела курсор на полной скорости, и он отскакивает назад/вперёд. Поэтому скорость
//   ставится штатно — `SystemParametersInfo(SPI_SETMOUSESPEED)` — и ТОЛЬКО на время, пока окно игры активно:
//     • без `SPIF_UPDATEINIFILE` — в реестр не пишется (после выхода из учётной записи Windows вернёт своё сама);
//     • окно игры потеряло фокус (Alt+Tab, сворачивание) — скорость игрока возвращается; вернулся фокус — ставится снова;
//     • выход из игры и падение процесса — возврат (`OnPreExit`, `OnHandleSystemError`); если процесс убит без обработчиков —
//       скорость вернёт следующий запуск по метке профиля `CursorSpeedRestoreLevel`;
//     • 100 % — системная скорость не трогается вовсе (умолчание: у игрока, не открывавшего настройки, Windows не меняется).
//   Процент считается от СОБСТВЕННОЙ скорости игрока (уровень 1…20 из «Параметров указателя»): множитель уровня по таблице
//   Windows × процент → ближайший уровень (сравнение по отношению, а не по разности: шкала неравномерна).
//   В редакторе (и в PIE) не работает: окно редактора — рабочее место владельца, глобальную скорость мыши там не меняем.
//   Без окна (`-RenderOffscreen` прогонов агентов) — тоже: системной скорости нечего «принадлежать».
#pragma once

#include "CoreMinimal.h"

struct ASDAREBORN_API FAsdaCursorSpeed
{
	// Один раз на процесс (зовёт `UAsdaSystemOptionSubsystem::Initialize`): вернуть долг прошлого запуска по метке профиля,
	//   подписаться на активацию окна, выход и падение, применить текущее значение профиля. Повторный вызов — ничего.
	static void Startup();
	// Вернуть скорость Windows и отписаться (`UAsdaSystemOptionSubsystem::Deinitialize`).
	static void Shutdown();
	// Перечитать поле профиля `CursorSpeedPercent` и привести системную скорость в соответствие (после «ОК/Применить»).
	static void Refresh();

	// ── Чистые функции (самотест) ──
	// Множитель скорости уровня Windows 1…20 (таблица «Параметров указателя»: 10 = ×1, 6 = ×0.5, 14 = ×2, 20 = ×3.5).
	static float LevelMultiplier(int32 Level);
	// Уровень Windows, ближайший к «уровень игрока × Percent %» (1…20).
	static int32 LevelForPercent(int32 BaseLevel, int32 Percent);
	// Текущий уровень указателя Windows 1…20 (0 — не прочитался / не Windows) — самотест сверяет, что прогон без окна его не трогал.
	static int32 ReadWindowsLevel();
	// Строка состояния для журнала/самотеста.
	static FString Describe();
};
