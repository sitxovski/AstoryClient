// ★★★ ВОЛНА Ф4 (10.09.2026): ЦВЕТ, РАДИУС И ПОЗИЦИЯ СЧИТАЮТСЯ ПО ВСЕМ ЖИВЫМ ЭМИТТЕРАМ, А НЕ ПО ОДНОМУ ДОНОРУ.
//
//   ЧТО БЫЛО НЕ ТАК. Волна Ф2 выбирала ОДИН эмиттер-донор (самый «светимый» по данным узлов) и брала у него
//   всё: цвет, радиус, позицию. У эффекта из нескольких эмиттеров разных цветов это произвол — какой донор
//   выбрался, такой и свет; а когда донор догорал раньше остальных, свет менял цвет или гас на живом эффекте.
//
//   ЧТО СТАЛО. Каждый живой эмиттер входит в агрегат со СВОИМ ВЕСОМ:
//       A_i = Verts_i · HalfExtent_i²        — прокси излучающей ПЛОЩАДИ секции (см. EmitterSectionStats)
//       L_i = 0.2126·R + 0.7152·G + 0.0722·B — ЯРКОСТЬ цвета узла (нормаль Rec.709, ненормированная)
//       g_i = A_i · L_i                      — «сколько света эмиттер способен дать» без учёта догорания
//       w_i = g_i · α_i                      — ВКЛАД этого кадра (площадь × яркость × альфа)
//   Позиция  P = Σ w_i·C_i / Σ w_i           — центр тяжести ПО ВКЛАДУ, а не середина коробки
//   Радиус   R = max_i(|P − C_i| + R_i)      — габарит ОБЪЕДИНЕНИЯ секций вокруг P
//   Альфа    α = min(1, Σ w_i / max_i g_i)   — ПОТОК, нормированный на САМЫЙ СИЛЬНЫЙ эмиттер: догоревший
//            эмиттер не гасит живых, и многоэмиттерный эффект НЕ ОКАЗЫВАЕТСЯ ТЕМНЕЕ одноэмиттерного.
//            ★ Средняя (Σ w / Σ g), стоявшая здесь до замера 10.09, давала ровно обратное: навык из 45
//            эмиттеров светил 2.14 кд против 6.40 кд у донора, освещённость пола 40.6 → 14.4
//   Цвет     — Mean или Median (см. EAsdaFxLightColorMode)
//   ★ У ОДНОЭМИТТЕРНОГО ЭФФЕКТА ВСЕ ТРИ ФОРМУЛЫ ТОЖДЕСТВЕННО РАВНЫ ПРЕЖНИМ (P = C_1, R = R_1, α = α_1) —
//     именно поэтому принятые волной Ф3 числа столбов alpen и фонаря nightvalley не могли сдвинуться.

