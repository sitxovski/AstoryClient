//   в пятнадцать метров освещает как лампочка. Это не настройка яркости и не радиус — это ФОРМА: у
//   светящейся плоскости освещённость вдоль плоскости почти не спадает, а перпендикулярно — спадает
//   как у точки. Никакими радиусами точечного источника это не воспроизводится.
//
//   ЧТО ДАЁТ ДВИЖОК. Три класса локальных источников, у каждого СВОЙ проход рендера и своя цена:
