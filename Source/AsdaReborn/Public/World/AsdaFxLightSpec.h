// ★★★ ВОЛНА Ф8 (10.09.2026): ФОРМА ИСТОЧНИКА.
//
//   ПОВОД — РАДУГА. `eff_rainbow_a_00` (alpen) — ПЛОСКАЯ ЛЕНТА длиной ~1500 юн и толщиной в один квад.
