//     * `URectLightComponent`   — прямоугольник (светящаяся плоскость), излучает в полусферу вдоль
//       СВОЕЙ оси +X; ширина по Y, высота по Z. Тень тоже кубическая.
//     * `USpotLightComponent`   — конус. Тень = ОДНА грань, поэтому теневой прожектор в ШЕСТЬ раз
//       дешевле теневой точки, и это единственный способ дать настенной лампе тень по цене, которую
//       не жалко (замер §4 отчёта Reports/fx_emitter_light/).
//   Класс источника выбирается КЛАССОМ КОМПОНЕНТА и во время работы не меняется, поэтому наш
//   `UAsdaFxLightComponent` (он же точечный) при не-точечной форме гасит себя и ведёт ДОЧЕРНИЙ
//   компонент нужного класса. Подсистема, бюджеты, отбор и дамп продолжают видеть ОДИН кандидат.
