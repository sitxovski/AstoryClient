// Очередь поштучной покупки: что ещё не отправлено и как идёт запуск. Владелец — подсистема окна (своя у каждого магазина).
struct FAsdaPremiumBuyQueue
{
	TArray<int32> Left;        // коды позиций, ещё не отправленные (по порядку корзины)
	int32 Total = 0;           // позиций в запуске
	int32 Sent = 0;            // сколько уже отправлено
	int32 Ok = 0;              // сколько подтверждено ответом 5071 с кодом 1
	bool  bRun = false;        // запуск идёт (с первой отправки до последнего ответа / остановки)
	bool  bSendNext = false;   // ответ 5071 код 1 принят — следующую позицию отправит Tick

	// Начать запуск по списку кодов (пустой список — запуск не начинается).
	void Start(const TArray<int32>& Codes)
	{
		Left = Codes;
		Total = Codes.Num();
		Sent = 0;
		Ok = 0;
		bRun = Total > 0;
		bSendNext = false;
	}
	// Есть ли ещё неотправленные позиции.
	bool HasMore() const { return Left.Num() > 0; }
	// Взять следующую позицию (0 = нечего).
	int32 PopNext()
	{
		if (Left.Num() == 0) { return 0; }
		const int32 Code = Left[0];
		Left.RemoveAt(0);
		++Sent;
		return Code;
	}
	// Закончить / прервать запуск.
	void Stop()
	{
		Left.Reset();
		Total = 0;
		Sent = 0;
		Ok = 0;
		bRun = false;
		bSendNext = false;
	}
};
