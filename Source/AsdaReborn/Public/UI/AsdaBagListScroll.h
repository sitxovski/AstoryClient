// РЕШЕНИЕ (решение владельца 29.10, без правки разметки и без рантайм-правки геометрии виджетов): модель окна держит
//   ПОЛНЫЙ уплотнённый список (до 60 позиций), сетка показывает его окно в 30 позиций, начиная с ряда `Row`;
//   колесо над сеткой сдвигает окно на ряд (6 позиций). При ≤ 30 подходящих вещах `MaxRow() == 0` — поведение
//   совпадает с эталоном один в один.
// Компонент без UObject — только числа; окно-владелец само решает, «над сеткой ли курсор», и перерисовывает себя.
#pragma once

#include "CoreMinimal.h"

// Окно в 30 позиций над уплотнённым списком (сетка 6 столбцов × 5 рядов).
struct FAsdaBagListScroll
{
	static constexpr int32 kCols    = 6;              // столбцов сетки окна-потребителя (данные `.JUI`, шаг 33)
	static constexpr int32 kRows    = 5;              // видимых рядов
	static constexpr int32 kVisible = kCols * kRows;  // видимых позиций (= прежняя ёмкость сетки окна)

	int32 Row   = 0;   // первый видимый ряд списка (0 = как эталон)
	int32 Total = 0;   // длина уплотнённого списка (сколько подходящих вещей нашлось)

	// Наибольший первый ряд: всего рядов − видимых (≥ 0).
	int32 MaxRow() const { return FMath::Max(0, FMath::DivideAndRoundUp(Total, kCols) - kRows); }

	// Индекс в списке первой видимой позиции.
	int32 First() const { return Row * kCols; }

	// Видимая ячейка → индекс в списке (без проверки длины списка).
	int32 ToList(int32 VisibleCell) const { return First() + VisibleCell; }

	// Индекс в списке → видимая ячейка (−1 — позиция сейчас за пределами окна).
	int32 ToVisible(int32 ListIndex) const
	{
		const int32 V = ListIndex - First();
		return (ListIndex >= 0 && V >= 0 && V < kVisible) ? V : -1;
	}

	// Новая длина списка: ряд клампится, чтобы окно не уехало за конец (вещь ушла — список укоротился).
	void SetTotal(int32 InTotal) { Total = FMath::Max(0, InTotal); Row = FMath::Clamp(Row, 0, MaxRow()); }

	// Колесо: «от себя» (+1) = вверх по списку = меньший ряд (та же конвенция, что у сетки инвентаря).
	//   true — ряд сменился (владелец перерисовывает сетку).
	bool Wheel(int32 Notches)
	{
		const int32 New = FMath::Clamp(Row - Notches, 0, MaxRow());
		if (New == Row) { return false; }
		Row = New;
		return true;
	}

	// Сброс (открытие окна, сброс сессии).
	void Reset() { Row = 0; Total = 0; }
};
