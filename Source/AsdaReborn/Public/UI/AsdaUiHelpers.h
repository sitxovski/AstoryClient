	//   прочистить якорь (мёртвые и отвязанные от `W`), добавить.
	template<typename RelayArrayT, typename ObjT>
	void AnchorRelay(RelayArrayT& Anchor, ObjT* Obj, UObject* W)
	{
		if (!Obj) { return; }
		MarkRelayBound(Obj, W);
		PruneAnchor(Anchor, W);
		Anchor.Add(Obj);
	}
