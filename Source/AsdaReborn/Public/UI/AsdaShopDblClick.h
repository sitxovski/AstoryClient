// ЧТО БЫЛО. В каждом магазине товар уходил в корзину / список покупки с ОДИНОЧНОГО щелчка
//   (у части окон — как в оригинале, у части — по ошибке порта). Владелец: «во всех магазинах предмет
//   попадает в корзину после одиночного щелчка, а должен — по двойному».
// ЧТО СТАЛО. Одиночный щелчок только ВЫДЕЛЯЕТ (рамка/курсор/подсказка — что у окна есть), второй щелчок
//   по ТОМУ ЖЕ узлу в пределах системного окна двойного щелчка Windows (`GetDoubleClickTime`) кладёт
//   в корзину РОВНО ОДИН раз: после срабатывания защёлка сбрасывается, третий щелчок снова «первый».
//   Перетаскивание в корзину (где оно есть) не затронуто — бросок кладёт сразу, как прежде.
// [ПОРТ] КЛЮЧ ОТКАТА: `asda.Shop.DblClickToCart 0` — прежнее поведение (одиночный щелчок кладёт).
//   У магазина NPC (окно 1300) двойной щелчок — это и есть ЭТАЛОН (0xB выбор / 0xD в корзину, `uiHandleWindowCommand@0xE24DE0`),
//   у премиум-магазина, магазина снаряжения и лавки игрока — отступление [ПОРТ] (эталон кладёт по одиночному 0xB).
//   Разбор по окнам и эталону — `Reports/owner_1010/shop_dblclick.md`.
//
// Почему своя структура, а не латч окна склада/обмена: там те же три строки «тот же узел + время» были
//   написаны трижды с разными порогами (0,35 с у склада, `GetDoubleClickTime` у обмена и книги рыб).
//   Здесь — один раз и с системным порогом (закон `port-shared-points`).
