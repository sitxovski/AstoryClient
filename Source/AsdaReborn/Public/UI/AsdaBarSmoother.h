// AsdaBarSmoother.h — общий сглаживатель полос здоровья и щитов.
//
// Отдельный лёгкий заголовок, потому что механизм нужен трём разным потребителям: полосам
// интерфейса игрока (`AsdaMiniStateSubsystem`), панели цели (`AsdaTargetFrameSubsystem`) и
// плашкам над персонажами (`AsdaNameplateComponent`). Тянуть ради него подсистему целиком в
// компонент плашки нельзя — получится встречное включение.
#pragma once

#include "CoreMinimal.h"

// ═══════════════ ★ ПЛАВНОЕ ИЗМЕНЕНИЕ ПОЛОС ЗДОРОВЬЯ И ЩИТОВ (общий механизм) ══════════════════
//  ★ ОТСТУПЛЕНИЕ ОТ ОРИГИНАЛА (заявка владельца 24.08.2026). В игре 2008 года полоса
//  перерисовывается мгновенно: получили число — нарисовали. Владелец попросил сделать движение
//  плавным, но БЫСТРЫМ: чтобы момент лечения нельзя было проморгать, а заливка при этом не
//  «ползла». Ключ отката к мгновенной отрисовке: `asda.UI.BarSmoothSec 0`.
//
//  Механизм ОДИН на все полосы — плашки над своим персонажем, над чужими, над монстрами, полосы
//  в интерфейсе игрока и в панели цели. Второй такой заводить нельзя: разъедется скорость.
//
//  Как считает. Скорость ПРОПОРЦИОНАЛЬНА оставшейся разнице: чем сильнее показанное значение
//  отстало от настоящего, тем быстрее идёт заливка. Большой удар «сносит» полосу почти сразу,
//  мелкий тик урона или лечения проходит мягко — но оба заканчиваются примерно за одно и то же
//  время, так что момент лечения не проморгать. Формула — экспоненциальное приближение с
//  постоянной времени `asda.UI.BarSmoothSec`:
//
//      Показано += (Цель − Показано) × (1 − exp(−Δt / Тау))
//
//  Плюс нижний предел скорости, иначе экспонента бесконечно ползёт «хвостом»: остаток дорисован
//  за то же время, что и полная шкала при самом медленном ходе. Разница меньше половины процента
//  дорисовывается сразу.
struct FAsdaBarSmoother
{
	float Shown = -1.f;    // что нарисовано сейчас (−1 = ещё ни разу не рисовали)
	float Target = 0.f;    // куда идём

	// Задать цель. Первый вызов рисует сразу — на появлении цели полоса не должна «наливаться».
	void SetTarget(float InTarget)
	{
		Target = FMath::Clamp(InTarget, 0.f, 1.f);
		if (Shown < 0.f) { Shown = Target; }
	}

	// Сбросить (цель снята, актор исчез) — следующий показ будет мгновенным.
	void Reset() { Shown = -1.f; Target = 0.f; }

	// Шаг сглаживания. Возвращает true, если картинку надо перерисовать.
	// `SmoothSec <= 0` — мгновенно, ровно как в оригинале.
	bool Advance(float DeltaSeconds, float SmoothSec)
	{
		if (Shown < 0.f) { Shown = Target; return true; }
		if (Shown == Target) { return false; }
		if (SmoothSec <= 0.f || DeltaSeconds <= 0.f) { Shown = Target; return true; }

		const float Diff = Target - Shown;
		if (FMath::Abs(Diff) < 0.005f) { Shown = Target; return true; }   // хвост — сразу

		// Основной ход: доля разницы за кадр. Скорость растёт вместе с разницей.
		float Step = FMath::Abs(Diff) * (1.f - FMath::Exp(-DeltaSeconds / SmoothSec));
		// Нижний предел: даже у самой мелкой разницы полоса не «замирает».
		const float MinStep = DeltaSeconds / (SmoothSec * 4.f);
		Step = FMath::Max(Step, MinStep);

		if (Step >= FMath::Abs(Diff)) { Shown = Target; }
		else { Shown += FMath::Sign(Diff) * Step; }
		return true;
	}

	// Время сглаживания из общей настройки (одно на весь интерфейс).
	static float SmoothSeconds();
};
