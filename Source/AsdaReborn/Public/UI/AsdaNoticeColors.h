#pragma once
#include "CoreMinimal.h"

namespace AsdaNoticeColor
{
	// −11514 = 0xFFFFD306 — золотой: основной системный цвет нотисов (отказы, итоги операций).
	inline constexpr FColor Gold(0xFF, 0xD3, 0x06, 0xFF);
	// −75279 = 0xFFFED9F1 — розовый: обмен, дуэль, меню игрока, хотбар (особые нотисы).
	inline constexpr FColor Pink(0xFE, 0xD9, 0xF1, 0xFF);
	// −2960896 = 0xFFD2D200 — оливковый: строки окна самоцветов (вставка/снятие/отказы гнёзд).
	inline constexpr FColor Olive(0xD2, 0xD2, 0x00, 0xFF);
}
