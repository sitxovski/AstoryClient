// ЧТО В ОРИГИНАЛЕ. Признак «второй раз до ответа не шлём» у эталона есть: например
//   `skillTree_SendLearnRequest@0xEE01A0` ставит `m_pSelSlot = (void*)1` (`skill_buff.c:38131`) и
//   снимает его первой строкой приёмника. ТАЙМАУТА у эталона нет — и не нужен: оригинал при
//   разрыве связи ПРОСТО ЗАКРЫВАЕТ КЛИЕНТ (память `original-quits-client-on-disconnect`), поэтому
//   «ответ не пришёл» у него означает «игры больше нет».
//
// ★ ЗАЧЕМ ТАЙМАУТ ПОРТУ — ОСОЗНАННОЕ ОТСТУПЛЕНИЕ. Порт при разрыве клиент не закрывает, а
//   отправка вдобавок ОТЛОЖЕНА на кадр (закон `no-reentrant-net-callbacks`). Если пакет не ушёл
//   или сервер промолчал, взведённый навсегда признак делает кнопку окна МЁРТВОЙ до «закрыть →
//   открыть», а в худшем случае — до переподключения (закон `no-state-latch-before-shown`).
//
// ★ ЗАЧЕМ ОБЩАЯ ТОЧКА. До 11.10.2026 засов жил в СЕМИ написаниях: `FAsdaInFlightLatch` (окна питомцев 43500/44200/42000,
//   `AsdaUiHelpers.h`, отсчёт `Left -= DeltaTime` по ИГРОВОМУ тику и таймаут, зафиксированный при взводе), свои пары
//   `bInFlight + InFlightSince` у разборки 6502, переплавки 6500, заточки 6504 и ремесла 6598…6604 (стенные часы, ключ
//   читается на каждом тике), `bCallRequestInFlight + CallInFlightLeft` вызова питомца 6100 (игровой тик) и
//   `bGmHidePending + GmHideSentAt` GM-команды «Скрыться» 6005 (стенные часы). Ключи и умолчания остаются у владельцев
//   (их знает владелец: `asda.*.ReplyTimeoutSec` 20, `asda.Pet.SendTimeoutSec` 20, `asda.Gm.HideAckTimeoutSec` 3).
//
// ★ ИСПРАВЛЕНИЕ (семантика времени, одна для всех): срок меряется СТЕННЫМИ часами (`FPlatformTime::Seconds`) от взвода, а
//   таймаут — значение ключа владельца НА МОМЕНТ ПРОВЕРКИ. Ответ сервера приходит в реальном времени, поэтому пауза,
//   замедление времени мира и провалы кадров срок ожидания больше не растягивают (раньше так было у питомцев), а правка
//   ключа на ходу действует сразу (раньше у питомцев — только со следующего взвода). У разборки, переплавки, заточки,
//   ремесла и GM-команды семантика та же, что была.
#pragma once

#include "CoreMinimal.h"
#include "HAL/PlatformTime.h"

struct FAsdaReplyLatch
{
	// Засов взведён — запрос ушёл, ответа ещё нет; повторную отправку не делаем.
	bool bArmed = false;
	// Момент взвода, секунды `FPlatformTime::Seconds()` (стенные часы). Живёт и после снятия — для строк лога.
	double ArmedAt = 0.0;
	// Опкод запроса, которым взведён засов (0 — владельцу не нужен). Живёт до следующего взвода.
	int32 Opcode = 0;

	// ★★★ ПРИЗНАК «ТАЙМАУТ УЖЕ СРАБАТЫВАЛ» (волна 8 питомцев, среднее 7).
	//   Гонка «таймаут снял засов — ответ сервера пришёл следом» должна быть ВИДНА, а не угадана (закон
	//   `false-negatives-method`). Признак ставит только `TickTimeout`, живёт до прихода ответа, и приёмник обязан
	//   СНЯТЬ его ЧТЕНИЕМ (`ConsumeTimedOut`), напечатав предупреждение.
	bool bTimedOut = false;

	// ★★★ КЛЮЧ ЗАПРОСА ДЛЯ СВЕРКИ ЭХА (волна 9 питомцев, поправка ревизии).
	//   Ответы пет-протокола несут КОРРЕЛЯЦИОННОЕ ЭХО запроса (разбор сборщиков сервера):
	//     6101 `+5..8`  petUid                       (`GameServer.c:34457`, `:34476`, `:34492`)
	//     6103 `+5..13` контейнер+слот трёх материалов (`:36740-36744`)
	//     6109 `+4..7`  petUid                       (`:35786`)
	//     6111 `+4..7`  petUid, обе ветки            (`:35852-35854`, `:35893-35927`)
	//     6113 `+50..55` младшие 16 бит трёх petUid  (`:35984-35985`)
	//     6119 `+4..7`  petUid                       (`:36255-36278`)
	//     6122 `+6..8`  контейнер+слот               (`:36444-36447`)
	//     6149 `+0..3`  petUid и `+45..47` слот+контейнер (`:36841-36843`)
	//   МОНОТОННОГО номера (seq) в протоколе нет. Сверка эхо-поля РАЗВОДИТ два запроса по РАЗНЫМ питомцам/ячейкам:
	//   ответ с чужим эхом — это ответ на ПРЕДЫДУЩИЙ запрос, снимать им засов текущего НЕЛЬЗЯ. Два ОДИНАКОВЫХ запроса
	//   (тот же питомец, та же ячейка) неразличимы — это и есть настоящий предел.
	//   `INDEX_NONE` — ключа нет, сверка не выполняется.
	int32 EchoKey = INDEX_NONE;

	// Взвести: запрос `InOpcode` ушёл сейчас. `InEchoKey` — чем ответ обязан «отозваться» (см. `EchoKey`).
	void Arm(int32 InOpcode = 0, int32 InEchoKey = INDEX_NONE)
	{
		bArmed = true;
		ArmedAt = FPlatformTime::Seconds();
		Opcode = InOpcode;
		bTimedOut = false;
		EchoKey = InEchoKey;
	}

	// Снять: пришёл ответ, сброс сессии, окно закрыли либо открыли заново.
	//   ⚠ `bTimedOut` ЗДЕСЬ НЕ ТРОГАЕТСЯ: его читает приёмник ответа уже ПОСЛЕ снятия засова.
	//   ⚠ `EchoKey`/`Opcode`/`ArmedAt` ТОЖЕ НЕ ТРОГАЮТСЯ: после таймаута ключ ПОСЛЕДНЕГО запроса обязан пережить снятие —
	//   иначе поздний ответ не с чем сверить. Их переписывает следующий `Arm`.
	void Disarm() { bArmed = false; }

	bool IsArmed() const { return bArmed; }

	// Сколько секунд засов взведён (0 — снят).
	double ElapsedSec() const { return bArmed ? FPlatformTime::Seconds() - ArmedAt : 0.0; }

	// Сколько секунд осталось до таймаута `TimeoutSec` (0 — снят, таймаута нет или истёк). Для строк лога/дампа.
	float RemainingSec(float TimeoutSec) const
	{
		if (!bArmed || TimeoutSec <= 0.f) { return 0.f; }
		return FMath::Max(0.f, TimeoutSec - (float)ElapsedSec());
	}

	// Срок вышел: взведён, `TimeoutSec > 0` (≤ 0 — без таймаута) и прошло СТРОГО больше. Засов не снимает — владелец
	//   снимает его своим путём (`ReleaseInFlight` с причиной в лог); для засова с признаком гонки — `TickTimeout`.
	bool IsExpired(float TimeoutSec) const
	{
		return bArmed && TimeoutSec > 0.f && (FPlatformTime::Seconds() - ArmedAt) > (double)TimeoutSec;
	}

	// Прокрутить таймаут: true — срок истёк ИМЕННО СЕЙЧАС (засов снят, `bTimedOut` взведён; вызывающий пишет в лог и
	//   оживляет кнопку). Дальнейшие вызовы true уже не вернут: засов снят.
	bool TickTimeout(float TimeoutSec)
	{
		if (!IsExpired(TimeoutSec)) { return false; }
		Disarm();
		bTimedOut = true;   // ★ ставится ПОСЛЕ `Disarm` — тот его сознательно не трогает
		return true;
	}

	// Ответ с эхом `ResponseEcho` — НЕ на наш запрос? true ⇒ эхо известно у обоих и РАЗОШЛОСЬ.
	//   Вызывающий обязан в этом случае НЕ снимать засов: его запрос всё ещё в полёте.
	bool IsForeignEcho(int32 ResponseEcho) const
	{
		return EchoKey != INDEX_NONE && ResponseEcho != INDEX_NONE && ResponseEcho != EchoKey;
	}

	// Прочитать и снять признак «таймаут уже срабатывал». true ⇒ ответ пришёл ПОЗЖЕ таймаута.
	bool ConsumeTimedOut() { const bool b = bTimedOut; bTimedOut = false; return b; }
};
