UAsdaFxLightComponent::UAsdaFxLightComponent()
{
	// Тик — в фазе эффекта (см. шапку заголовка); включает его подсистема при выдаче места в бюджете
	PrimaryComponentTick.bCanEverTick = true;
	PrimaryComponentTick.bStartWithTickEnabled = false;
	PrimaryComponentTick.TickGroup = TG_PostUpdateWork;
	// ★ ТИК В ОКНЕ РЕДАКТОРА. Эффекты в редакторском мире анимируются (ShouldTickIfViewportsOnly = true),
	//   и свет обязан идти за ними: иначе «показ в редакторе» дал бы неподвижное пятно от подвижного пламени,
	//   а правка ползунка яркости не была бы видна вовсе.
	bTickInEditor = true;

	// ИНВАРИАНТЫ ПРОЕКТА (те же, что ставит AAsdaLocalLightActor::ApplyInvariants):
	Mobility = EComponentMobility::Movable;      // r.AllowStaticLighting=False — Static/Stationary не светит вовсе
	IntensityUnits = ELightUnits::Candelas;      // Unitless непереносим между радиусами и картами (1 кд = 625)
	bUseInverseSquaredFalloff = true;            // иначе кандела нефизична и шкала яркости рассыпается
	CastShadows = false;                         // роль Glow: теней НИКОГДА (за это и не считаемся в бюджете теней)
	bCastVolumetricShadow = false;
	bUseRayTracedDistanceFieldShadows = false;
	bAffectsWorld = false;                       // рождаемся погашенными: место в бюджете ещё не выдано
	SetVisibility(false);
	bAffectGlobalIllumination = false;           // GI включает поле Spec.bAffectGI (по умолчанию нет: эффект живёт секунды, а surface cache Lumen обновляется медленнее)
}

const FAsdaFxLightRule* UAsdaFxLightComponent::GetRule() const
{
	const UAsdaFxLightSettings* S = UAsdaFxLightSettings::Get();
	return S->Families.IsValidIndex(RuleIndex) ? &S->Families[RuleIndex] : nullptr;
}
