// ★★★ РЕВИЗИЯ fix3 (М-2, 20.09.2026): ОДНО ПРАВИЛО СОГЛАСОВАНИЯ ДЛИНЫ КУСКА И ЕГО РАДИУСА.
//   Затухание движка меряется от ЦЕНТРА источника, поэтому конец куска раскладки (дуги кольца,
//   полосы блина, капсулы трубки) обязан лежать внутри его собственной сферы затухания с запасом:
//       полу-длина куска ≤ ДОЛЯ · радиус_куска      ⇔      радиус_куска ≥ полу-длина / ДОЛЯ.
//   Доля 0.66 (треть радиуса в запас) введена ревизией Ф11 у блина и признана правильной: ниже неё
//   стыки кусков темнеют. До этой ревизии кольцо жило по несогласованной паре «радиус = полу-хорда +
//   полрадиуса, длина ≤ 0.8 радиуса», а трубка — по «радиус ≥ полу-длина + 1 юн, длина не резалась
//   вовсе»: три формы, три разных правила для одного и того же геометрического условия.
static constexpr float ASDA_FX_SPLIT_HALFLEN_SHARE = 0.66f;

// GAsdaFxSplitMinGain: определение — в домашней части (R2).
extern float GAsdaFxSplitMinGain;

// ОДНО ПРАВИЛО ЧИСЛА ПЛИТОК — НА ОБЕ ВЕТКИ (раскладка SplitGeometry и счёт цены SplitSourceCount).
//   Довод, почему правило обязано быть ОДНИМ и применяться БУКВАЛЬНО дважды, — закон
//   port-shared-points: второй такой же расчёт рядом расходится с первым, и бюджет начинает
//   списывать не то, что горит (ровно этим был КРИТ-1 ревизии fix3).
//   HalfChord — полу-длина ВСЕГО куска (полосы блина, дуги кольца, капсулы трубки), юн.
//   OutR — радиус затухания ОДНОЙ плитки, юн. Возвращает число плиток.
static int32 AsdaFxTilesFor(float HalfChord, float R0, float CapR, int32 TileCap, float& OutR)
{
	int32 Tiles = 1;
	OutR = FMath::Min(FMath::Max(R0, HalfChord / ASDA_FX_SPLIT_HALFLEN_SHARE), CapR);
	for (int32 c = 1; c <= TileCap; ++c)
	{
		const float Half = HalfChord / (float)c;
		const float Rc = FMath::Min(FMath::Max(R0, Half / ASDA_FX_SPLIT_HALFLEN_SHARE), CapR);
		Tiles = c; OutR = Rc;
		if (Half <= Rc * ASDA_FX_SPLIT_HALFLEN_SHARE + KINDA_SMALL_NUMBER) { break; }
	}
	// ★ fix6 (МЕЛК-5): дробление, которое ничего не накрывает, — только трата мест бюджета
	if (Tiles > 1 && HalfChord > KINDA_SMALL_NUMBER && GAsdaFxSplitMinGain > 0.f)
	{
		const float CoveredHalf = (float)Tiles * OutR * ASDA_FX_SPLIT_HALFLEN_SHARE;   // светящаяся полу-длина
		if (CoveredHalf < GAsdaFxSplitMinGain * HalfChord)
		{
			Tiles = 1;
			OutR = FMath::Min(FMath::Max(R0, HalfChord / ASDA_FX_SPLIT_HALFLEN_SHARE), CapR);
		}
	}
	return Tiles;
}

