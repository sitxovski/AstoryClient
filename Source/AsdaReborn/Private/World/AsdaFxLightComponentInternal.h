// ★★★ ВОЛНА Ф8 (10.09.2026): ФОРМА ИСТОЧНИКА — ТОЧКА / ПРЯМОУГОЛЬНИК / КОНУС.
//
//   ПОЧЕМУ ДОЧЕРНИЕ КОМПОНЕНТЫ, А НЕ ТРИ КЛАССА НАШЕГО КОМПОНЕНТА. Класс источника в движке решает
//   его сцен-прокси, а прокси выбирается КЛАССОМ КОМПОНЕНТА и во время работы не меняется. Владелец
//   же крутит форму в панели деталей на живой сцене. Три родственных класса означали бы три копии
//   всей логики кадра (гейты, бюджет, тень, мерцание) либо интерфейс поверх них — и, главное,
//   переписанные подсистему, отбор, дамп и все консольные команды. Дочерний компонент даёт то же
//   самое за двадцать строк: НАШ компонент остаётся ЕДИНСТВЕННЫМ кандидатом, а рисует за него тот
//   класс, который умеет нужную форму. Погашенный точечный (bAffectsWorld=false) в сцену не попадает
//   вовсе, поэтому «лишний» компонент рендеру не стоит ничего.
// ═══════════════════════════════════════════════════════════════════════════════════════════════════
// Общая настройка ЛЮБОГО дочернего источника — ровно та же, что у нас самих в конструкторе.
// Разъехаться этим двум наборам нельзя: иначе прямоугольник светил бы в других единицах, чем точка,
// и «6.» кандел означало бы для двух форм разную яркость.
static void AsdaInitFxChildLight(ULocalLightComponent* L)
{
	if (!L) { return; }
	L->SetMobility(EComponentMobility::Movable);      // r.AllowStaticLighting=False — Static/Stationary не светит
	L->IntensityUnits = ELightUnits::Candelas;        // та же кандела, что у точечной формы
	L->CastShadows = false;                           // тень включает отдельное поле, через бюджет теней
	L->bCastVolumetricShadow = false;
	L->bUseRayTracedDistanceFieldShadows = false;
	L->bAffectsWorld = false;                         // рождаемся погашенными
	L->SetVisibility(false);
	L->bAffectGlobalIllumination = false;
}

// Погасить источник, который сейчас не выбран формой (или все — при Extinguish).
static void AsdaDouseLight(ULocalLightComponent* L)
{
	if (!L || !L->bAffectsWorld) { return; }
	L->bAffectsWorld = false;
	L->SetVisibility(false);
	L->MarkRenderStateDirty();
}
