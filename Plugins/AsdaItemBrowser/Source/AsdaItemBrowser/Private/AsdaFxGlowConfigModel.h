// Вид узла дерева конфигуратора
enum class EAsdaGlowNodeKind : uint8
{
	Group,        // корень группы («Глобальные семейства», «Лут», «Оружие и щиты») или класс оружия
	Family,       // правило-семейство таблицы
	Effect,       // эффект без предмета (блёстки дропа, эффект карты/навыка) — запись overrides с item_id 0
	Item,         // предмет (оружие/щит) — контейнер ступеней
	ItemState,    // ступень свечения предмета (+5/+6/+7) — свой .jeb
	// ★★★ ВОЛНА Р1 (20.09.2026): ЭМИТТЕР ВНУТРИ ЭФФЕКТА. Его настройки свечения лежат НЕ в таблице
	//   Tools/asda_fx_light.json, а В САМОМ АССЕТЕ (AAsdaEffectActor::Emitters[i].Glow + долговечная копия
	//   EmitterGlowSaved), поэтому у них свой путь правки — мимо FAsdaGlowEditState и мимо «Сохранить».
	Emitter,
};

// Узел дерева
struct FAsdaGlowNode
{
	EAsdaGlowNodeKind Kind = EAsdaGlowNodeKind::Group;   // вид узла
	FString Label;                 // подпись строки
	FString FamilyId;              // семейство (Family) или семейство, под которое попал .jeb
	FString Jeb;                   // имя .jeb (Effect / ItemState)
	int32 ItemCode = 0;            // код предмета (Item / ItemState)
	int32 ItemIndex = INDEX_NONE;  // глобальный индекс записи FAsdaItemBrowserData (для превью модели)
	int32 Enhance = 0;             // ступень заточки 5/6/7 (ItemState)
	FString FxClassPath;           // путь класса BP_Fx_… для превью ("" — ассета нет)
	int32 Count = 0;               // предметов/записей в ветке
	bool bHasOverride = false;     // на узле (или у его ступеней) есть сохранённые переопределения
	// ★ Волна Р1 (п.8): у узла (или его ветки) есть НЕсохранённые правки — для фильтра «только изменённые»
	bool bDirty = false;
	// ★★★ Ревизия Ф12 (С3): ТРЕТЬЕ СОСТОЯНИЕ ОТМЕТКИ — «НЕ ЗНАЮ» (в дереве «?»).
	//   Поэмиттерные числа лежат В АССЕТЕ, и прочитать их можно только у загруженного класса
	//   (грузить 1283 класса ради отметки нельзя). Прежде незагруженный класс давал ● = нет, то
	//   есть УВЕРЕННОЕ «правок нет» — ровно то ложное «нет», против которого закон
	//   false-negatives-method. Теперь незнание называется незнанием.
	bool bMarkUnknown = false;
	// ★ Волна Р1 (п.7): номер эмиттера в AAsdaEffectActor::Emitters (только у узлов вида Emitter)
	int32 EmitterIndex = INDEX_NONE;
	// ★ Волна Р1 (п.7): список эмиттеров ещё не построен. Ассет грузится ТОЛЬКО при раскрытии узла —
	//   иначе открытие вкладки тянуло бы в память все 1283 класса BP_Fx_* разом
	bool bNeedEmitters = false;
	TArray<TSharedPtr<FAsdaGlowNode>> Children;   // дочерние узлы (классы, предметы, ступени, эмиттеры)
};

// ★★★ ВОЛНА Р1 (20.09.2026): ССЫЛКА НА ЭМИТТЕР ВНУТРИ АССЕТА ЭФФЕКТА.
//   Отдельный тип, а не FAsdaGlowTarget: цель FAsdaGlowTarget адресует запись в Tools/asda_fx_light.json,
//   а эмиттер адресует поле В АССЕТЕ. Смешать их в одном типе значило бы дать «Сохранить» обещание,
//   которого он выполнить не может (ассеты он не пишет и писать не должен).
struct FAsdaGlowEmitterRef
{
	FString ClassPath;             // путь класса BP_Fx_… ассета-владельца
	int32 Index = INDEX_NONE;      // номер эмиттера в массиве Emitters

	bool IsValid() const { return Index != INDEX_NONE && !ClassPath.IsEmpty(); }
};

// Куда ложится правка
struct FAsdaGlowTarget
{
	bool bFamily = false;          // true — семейство FamilyId; false — запись overrides (Jeb, ItemId)
	FString FamilyId;              // id семейства (только при bFamily)
	FString Jeb;                   // точное имя .jeb записи overrides (только при !bFamily)
	int32 ItemId = 0;              // 0 — эффект у всех предметов
	FString Label;                 // человеческое имя (пишется в JSON рядом с записью)

	// Ключ цели в картах состояний и экспорта: «F|id» или «O|jeb|код»
	FString Key() const { return bFamily ? (TEXT("F|") + FamilyId) : FString::Printf(TEXT("O|%s|%d"), *Jeb.ToLower(), ItemId); }
	// Цель задана (узел-группа даёт невалидную)
	bool IsValid() const { return bFamily ? !FamilyId.IsEmpty() : !Jeb.IsEmpty(); }
};

// Описание поля таблицы (из SPEC_FIELDS генератора, через экспорт)
struct FAsdaGlowField
{
	FName CppName;                 // имя поля FAsdaFxLightSpec
	FString JsonKey;               // ключ JSON
	FString Type;                  // b f i e_* c v r
	FProperty* Prop = nullptr;     // свойство структуры (nullptr — поле не найдено: сборка разошлась с генератором)
	bool bAdvanced = false;        // показывать в свёрнутом блоке «Дополнительно»
	// ★ Волна Р0 (п.2): номер раздела панели (FAsdaFxGlowConfigModel::GetSections)
	int32 Section = 0;
	// ★ Волна Р0 (пп.3 и 5): подпись БЕЗ номера и с поправками имён — собирается один раз при разборе экспорта
	FString Label;
	// ★ Волна Р0 (п.5): подсказка с поправкой (уточнение волны Р0 + исходный ToolTip свойства)
	FString Tip;
	// ★ Волна Р0 (п.1): meta EditCondition свойства («» — поле работает всегда) и meta EditConditionHides.
	//   ★ Ревизия Ф11 (С1): САМО выражение теперь считает штатный EditConditionEvaluator движка,
	//   а эта строка осталась быстрым признаком «условие вообще есть» и материалом для отчётов
	FString EditCondition;
	bool bEditConditionHides = false;
	// ★★★ РЕВИЗИЯ Ф11 (С4): ПОЛЕ ВИДНО, НО ЗАПИСАТЬ ЕГО ОТСЮДА НЕЛЬЗЯ.
	//   Такое поле в таблице SPEC_FIELDS генератора есть (значит, молча пропасть из панели оно не
	//   должно), но путь записи ведёт не сюда: `bManual` — ЗАМОК САМОГО АССЕТА, и генератор ini
	//   пишет у записей таблицы всегда False (Tools/asda_gen_fx_light_ini.py:326 — чужой файл).
	//   Показываем его серым, с объяснением, и без кнопки «Сброс»: врать «правится» нельзя.
	bool bReadOnly = false;
};

// Состояние одной цели правки: текущие числа (живые), дефолты, свои ключи и несохранённое
struct FAsdaGlowEditState
{
	FAsdaGlowTarget Target;                 // чья это правка
	FAsdaFxLightSpec Work;                  // что действует сейчас (с несохранёнными правками)
	FAsdaFxLightSpec Defaults;              // значение каждого поля «если ключа нет» (наследуемое)
	TSet<FName> DefaultUnset;               // поля без дефолта вовсе (сила свечения: «из материала»)
	TSet<FName> SavedOwn;                   // свои ключи в сохранённом JSON
	TSet<FName> PendingSet;                 // изменено, не сохранено
	TSet<FName> PendingReset;               // сброшено к дефолту, не сохранено
	bool bPendingRemove = false;            // снять запись целиком (только overrides)
	bool bExistsSaved = false;              // запись уже есть в JSON (для overrides)

	// Поле задано самой записью (с учётом несохранённого)
	bool IsOwn(FName F) const { return !PendingReset.Contains(F) && (PendingSet.Contains(F) || (SavedOwn.Contains(F) && !bPendingRemove)); }
	// Есть несохранённые правки
	bool IsDirty() const { return PendingSet.Num() > 0 || PendingReset.Num() > 0 || bPendingRemove; }
};

